const countryFlags: Record<string, string> = {
  SY: '🇸🇾',
  LB: '🇱🇧',
  TR: '🇹🇷',
  JO: '🇯🇴',
};

function detectLanguage(): Language {
  if (typeof window === 'undefined') return 'ar';
  const stored = window.localStorage.getItem('rivia-language') || window.localStorage.getItem('language');
  const htmlLang = document.documentElement.lang;
  const candidate = (stored || htmlLang || navigator.language || 'ar').toLowerCase();
  return candidate.startsWith('en') ? 'en' : 'ar';
}

export function getTextDirection(language: Language): TextDirection {
  return language === 'ar' ? 'rtl' : 'ltr';
}

export function t(key: string, params?: TranslationParams, language: Language = detectLanguage()) {
  const template = translations[language][key] ?? translations.en[key] ?? key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, paramKey: string) => String(params[paramKey] ?? ''));
}

export function useTranslation() {
  const [language, setLanguage] = useState<Language>(() => detectLanguage());

  useEffect(() => {
    const updateLanguage = () => setLanguage(detectLanguage());
    window.addEventListener('storage', updateLanguage);
    window.addEventListener('rivia-language-change', updateLanguage);
    return () => {
      window.removeEventListener('storage', updateLanguage);
      window.removeEventListener('rivia-language-change', updateLanguage);
    };
  }, []);

  return useMemo(
    () => ({
      language,
      direction: getTextDirection(language),
      locale: language === 'ar' ? 'ar-SA' : 'en-US',
      t: (key: string, params?: TranslationParams) => t(key, params, language),
    }),
    [language],
  );
}

export function countryName(code: string, language: Language = detectLanguage()) {
  return t(`country.${code}`, undefined, language);
}

export function countryFlag(code: string) {
  return countryFlags[code] || '';
}

export function localizedCurrencyLabel(code: string, language: Language = detectLanguage()) {
  const label = t(`currency.${code}`, undefined, language);
  return label === `currency.${code}` ? code : `${code} - ${label}`;
}
